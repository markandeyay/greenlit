/** FNV-1a 32-bit. */
function fnv1a(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

export const SYNTHETIC_ID_BASE = 900_000_000;

/** Stable synthetic id for a person with no known TMDB id. */
export function syntheticPersonId(name: string): number {
  return SYNTHETIC_ID_BASE + (fnv1a(name.normalize('NFC')) % 90_000_000);
}

export function personIdFor(name: string): number {
  return KNOWN_PERSON_IDS[name] ?? syntheticPersonId(name);
}
